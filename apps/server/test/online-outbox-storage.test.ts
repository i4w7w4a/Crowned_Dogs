import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { test } from "node:test";
import { clock } from "./online-fixtures.ts";
import { gameFixture } from "./online-game-fixtures.ts";
import { SqlTelegramOutbox } from "../src/online/outbox.ts";
test("SQL outbox fences expired leases, orders updates and retains configured topic and message", async (t) => {
    const f = await gameFixture();
    t.after(() => f.close());
    let now = clock;
    const outbox = new SqlTelegramOutbox(f.database, () => now);
    const invite = (await f.game.createInvite(f.accounts[0]!.id, { commandId: randomUUID() }, now)).body.invite;
    const first = await outbox.claimDue(now, 1000);
    assert.ok(first);
    assert.equal(first.threadId, 566);
    assert.equal(await outbox.claimDue(now, 1000), null);
    await f.game.cancelInvite(f.accounts[0]!.id, invite.token, { commandId: randomUUID(), expectedVersion: 1 }, now);
    assert.equal(await outbox.claimDue(now, 1000), null);
    now += 1000;
    const retry = await outbox.claimDue(now, 1000);
    assert.ok(retry);
    assert.notEqual(retry.leaseId, first.leaseId);
    assert.equal(retry.card.status, "cancelled");
    assert.equal(await outbox.complete(first.leaseId, 77), false);
    assert.equal(await outbox.complete(retry.leaseId, 78), true);
    await f.reopen();
    const update = await outbox.claimDue(now, 1000);
    assert.ok(update);
    assert.equal(update.messageId, 78);
    assert.equal(update.threadId, 566);
    assert.equal(await outbox.fail(update.leaseId, { code: "telegram_rate_limited", retryAt: now + 2000 }), true);
    assert.equal(await outbox.claimDue(now, 1000), null);
    now += 2000;
    const due = await outbox.claimDue(now, 1000);
    assert.ok(due);
    assert.equal(due.messageId, 78);
    await outbox.fail(due.leaseId, { code: "telegram_topic_unavailable", retryAt: null });
    assert.equal((await f.game.invite(invite.token, now)).body.invite.delivery.status, "failed");
    assert.equal(await outbox.claimDue(now + 100000, 1000), null);
});
test("claim expires an invite before publishing even when the deadline loop was offline", async (t) => {
    const f = await gameFixture();
    t.after(() => f.close());
    const invite = (await f.game.createInvite(f.accounts[0]!.id, { commandId: randomUUID() }, clock)).body.invite;
    const outbox = new SqlTelegramOutbox(f.database, () => clock + 1800000);
    const due = await outbox.claimDue(clock + 1800000, 1000);
    assert.ok(due);
    assert.equal(due.card.status, "expired");
    assert.equal((await f.database.query("SELECT count(*)::int AS n FROM online_player_slots")).rows[0]!.n, 0);
    assert.equal((await f.game.invite(invite.token, clock + 1800000)).body.invite.status, "expired");
});
