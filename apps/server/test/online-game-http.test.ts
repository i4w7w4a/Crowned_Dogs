import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { test } from "node:test";
import { clock, botToken, initData } from "./online-fixtures.ts";
import { gameFixture } from "./online-game-fixtures.ts";
import { BrowserLoginService } from "../src/online/browser-login.ts";
import { createOnlineServer } from "../src/online/http.ts";
test("mounted HTTP connects confirmed browser and Mini App to the same persistent match", async (t) => {
    const f = await gameFixture();
    t.after(() => f.close());
    const origin = "https://game.example";
    const browserLogin = new BrowserLoginService(f.store, { origin, botUsername: "GameTestBot", clock: () => clock });
    const server = createOnlineServer({ store: f.store, game: f.game, browserLogin, botToken, origin, basePath: "/r2/api/online", production: true, now: () => clock });
    await new Promise<void>(resolve => server.listen(0, "127.0.0.1", resolve));
    t.after(() => new Promise<void>(resolve => { server.closeAllConnections(); server.close(() => resolve()); }));
    const address = server.address();
    assert.ok(address && typeof address !== "string");
    const base = `http://127.0.0.1:${address.port}/r2/api/online`;
    const post = (route: string, body: unknown, cookie = "", sentOrigin = origin) => fetch(base + route, { method: "POST", headers: { origin: sentOrigin, "content-type": "application/json", cookie }, body: JSON.stringify(body) });
    const get = (route: string, cookie = "") => fetch(base + route, { headers: { cookie } });
    const sign = await post("/auth/telegram", { initData: initData({ user: JSON.stringify({ id: 1, first_name: "Первый" }) }) });
    const cookieA = sign.headers.getSetCookie()[0]!.split(";")[0]!;
    assert.equal((await post("/invites", { commandId: randomUUID() })).status, 401);
    assert.equal((await post("/invites", { commandId: randomUUID() }, cookieA, "https://evil.example")).status, 403);
    assert.equal((await post("/invites", { commandId: randomUUID(), playerId: f.accounts[1]!.id }, cookieA)).status, 400);
    const invite = (await (await post("/invites", { commandId: randomUUID() }, cookieA)).json() as any).invite;
    const start = await post("/auth/browser/start", { inviteToken: invite.token });
    assert.equal(start.status, 200);
    const cookieBrowser = start.headers.getSetCookie()[0]!.split(";")[0]!;
    assert.match(start.headers.getSetCookie()[0]!, /HttpOnly/);
    assert.match(start.headers.getSetCookie()[0]!, /Path=\/r2\/api\/online/);
    const challenge = await start.json() as any;
    assert.equal(challenge.cookie, undefined);
    assert.equal((await post("/auth/browser/consume", {}, cookieBrowser)).status, 409);
    await browserLogin.confirm(challenge.challengeId, { id: "2", firstName: "Второй", lastName: null, username: null }, clock);
    assert.equal((await (await get("/auth/browser/status", cookieBrowser)).json() as any).status, "confirmed");
    assert.equal((await post("/auth/browser/consume", {})).status, 410);
    const consume = await post("/auth/browser/consume", {}, cookieBrowser);
    assert.equal(consume.status, 200);
    const consumed = await consume.json() as any;
    assert.equal(consumed.inviteToken, invite.token);
    assert.equal(consumed.account.id, f.accounts[1]!.id);
    assert.equal(consumed.token, undefined);
    const cookieB = consume.headers.getSetCookie().find(c => c.startsWith("cd_online_session="))!.split(";")[0]!;
    assert.equal((await post("/auth/browser/consume", {}, cookieBrowser)).status, 410);
    let battle = (await (await post(`/invites/${invite.token}/accept`, { commandId: randomUUID(), expectedVersion: 1 }, cookieB)).json() as any).battle;
    assert.equal(battle.side, 1);
    assert.equal(battle.phase, "loading");
    for (const cookie of [cookieA, cookieB]) {
        const r = await post(`/matches/${battle.id}/commands`, { commandId: randomUUID(), expectedVersion: battle.version, turn: 1, action: { type: "ready" } }, cookie);
        assert.equal(r.status, 200);
        battle = (await r.json() as any).battle;
    }
    assert.equal(battle.phase, "active");
    assert.ok(battle.deadline > clock);
    const request = { commandId: randomUUID(), expectedVersion: battle.version, turn: 1, action: { type: "surrender" } };
    const result = await (await post(`/matches/${battle.id}/commands`, request, cookieA)).json() as any;
    assert.equal(result.battle.phase, "finished");
    assert.equal(result.battle.reward.xp, 0);
    assert.deepEqual(await (await post(`/matches/${battle.id}/commands`, request, cookieA)).json(), result);
    assert.equal((await (await get(`/matches/${battle.id}`, cookieB)).json() as any).battle.result.winner, 1);
    assert.equal((await (await get("/matches", cookieA)).json() as any).matches.length, 1);
    assert.deepEqual((await (await get("/activity", cookieA)).json() as any).battle, null);
});
