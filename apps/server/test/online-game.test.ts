import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { test } from "node:test";
import { clock } from "./online-fixtures.ts";
import { gameFixture } from "./online-game-fixtures.ts";
import { OnlineGameService } from "../src/online/game-service.ts";
const intent = (version: number, action: unknown, turn = 1) => ({ commandId: randomUUID(), expectedVersion: version, turn, action });
test("persistent PvP serializes invite acceptance, retries commands and settles rewards once", async (t) => {
    const f = await gameFixture();
    t.after(() => f.close());
    const [a, b, c] = f.accounts;
    const created = await f.game.createInvite(a!.id, { commandId: randomUUID() }, clock);
    assert.equal(created.status, 200);
    const invite = created.body.invite;
    const accepted = await Promise.all([b!, c!].map(p => f.game.acceptInvite(p.id, invite.token, { commandId: randomUUID(), expectedVersion: invite.version }, clock + 1)));
    assert.equal(accepted.filter(r => r.status === 200).length, 1);
    assert.equal((await f.database.query("SELECT count(*)::int AS n FROM online_matches")).rows[0]!.n, 1);
    const win = accepted.find(r => r.status === 200)!;
    let battle = win.body.battle;
    const guest = battle.players[1].id;
    assert.equal(battle.phase, "loading");
    assert.equal(battle.deadline, null);
    const outsider = guest === b!.id ? c!.id : b!.id;
    assert.equal((await f.game.match(outsider, battle.id, clock + 2)).status, 404);
    battle = (await f.game.command(a!.id, battle.id, intent(battle.version, { type: "ready" }), clock + 2)).body.battle;
    assert.equal(battle.deadline, null);
    battle = (await f.game.command(guest, battle.id, intent(battle.version, { type: "ready" }), clock + 3)).body.battle;
    const choose = intent(battle.version, { type: "press", command: { type: "zone", zone: "head" } });
    const first = await f.game.command(a!.id, battle.id, choose, clock + 4);
    assert.equal(first.status, 200);
    assert.deepEqual(await f.game.command(a!.id, battle.id, choose, clock + 5), first);
    assert.equal((await f.game.command(a!.id, battle.id, { ...choose, action: { type: "submit" } }, clock + 6)).status, 409);
    battle = first.body.battle;
    for (const zone of ["head", "body"])
        battle = (await f.game.command(a!.id, battle.id, intent(battle.version, { type: "press", command: { type: "guard", zone } }), clock + 7)).body.battle;
    battle = (await f.game.command(a!.id, battle.id, intent(battle.version, { type: "submit" }), clock + 8)).body.battle;
    assert.equal(battle.own.submitted, true);
    await f.reopen();
    const reopened = new OnlineGameService(f.database, { chatId: "-1001", threadId: 566, clock: () => clock });
    battle = (await reopened.match(a!.id, battle.id, clock + 9)).body.battle;
    assert.equal(battle.own.order.action.zone, "head");
    const other = (await reopened.match(guest, battle.id, clock + 9)).body.battle;
    assert.equal(other.own.order, null);
    assert.equal(other.submitted[0], true);
    const wire = JSON.stringify(other);
    assert.ok(!wire.includes('"rng"'));
    assert.ok(!wire.includes('"seed"'));
    assert.ok(!wire.includes('"orders"'));
    const afterTurn = battle.deadline;
    await reopened.tick(afterTurn);
    battle = (await reopened.match(a!.id, battle.id, afterTurn)).body.battle;
    const finish = intent(battle.version, { type: "surrender" }, battle.match.turn);
    const done = await reopened.command(guest, battle.id, finish, afterTurn + 1);
    assert.equal(done.body.battle.phase, "finished");
    await reopened.command(guest, battle.id, finish, afterTurn + 2);
    await reopened.match(a!.id, battle.id, afterTurn + 3);
    assert.equal((await f.database.query("SELECT count(*)::int AS n FROM online_reward_ledger")).rows[0]!.n, 2);
    assert.equal((await f.database.query("SELECT count(*)::int AS n FROM online_player_slots")).rows[0]!.n, 0);
    const progress = (await f.database.query("SELECT profile FROM online_operators WHERE id=$1", [a!.id])).rows[0]!.profile;
    assert.ok(progress.level > 1 || progress.xp > 0);
    await f.database.query("UPDATE online_matches SET snapshot=jsonb_set(snapshot,'{match,result,privateFuture}','\"hidden\"') WHERE id=$1", [battle.id]);
    assert.ok(!JSON.stringify(await reopened.history(a!.id, afterTurn + 4)).includes("hidden"));
});
test("deadline race advances one turn and restart never catches up multiple AFK turns", async (t) => {
    const f = await gameFixture();
    t.after(() => f.close());
    const [a, b] = f.accounts;
    const invite = (await f.game.createInvite(a!.id, { commandId: randomUUID() }, clock)).body.invite;
    let battle = (await f.game.acceptInvite(b!.id, invite.token, { commandId: randomUUID(), expectedVersion: 1 }, clock)).body.battle;
    battle = (await f.game.command(a!.id, battle.id, intent(battle.version, { type: "ready" }), clock)).body.battle;
    battle = (await f.game.command(b!.id, battle.id, intent(battle.version, { type: "ready" }), clock)).body.battle;
    await f.game.tick(clock + 1);
    assert.equal((await f.game.match(a!.id, battle.id, clock + 1)).body.battle.match.turn, 1);
    const now = clock + 3600000;
    const [late] = await Promise.all([f.game.command(a!.id, battle.id, intent(battle.version, { type: "submit" }), now), f.game.tick(now)]);
    assert.ok([409, 410].includes(late.status));
    battle = (await f.game.match(a!.id, battle.id, now)).body.battle;
    assert.equal(battle.match.turn, 2);
    assert.equal(battle.match.history.length, 1);
    assert.ok(battle.deadline > now);
    await f.game.tick(now);
    assert.equal((await f.game.match(a!.id, battle.id, now)).body.battle.match.turn, 2);
});
test("failed reward persistence rolls back final snapshot, both profiles, slots and receipts", async (t) => {
    const f = await gameFixture();
    t.after(() => f.close());
    const [a, b] = f.accounts;
    const invite = (await f.game.createInvite(a!.id, { commandId: randomUUID() }, clock)).body.invite;
    let battle = (await f.game.acceptInvite(b!.id, invite.token, { commandId: randomUUID(), expectedVersion: 1 }, clock)).body.battle;
    for (const p of [a!, b!])
        battle = (await f.game.command(p.id, battle.id, intent(battle.version, { type: "ready" }), clock)).body.battle;
    await f.database.query("ALTER TABLE online_reward_ledger ADD CONSTRAINT reject_rewards CHECK(false) NOT VALID");
    const request = intent(battle.version, { type: "surrender" });
    await assert.rejects(f.game.command(a!.id, battle.id, request, clock));
    assert.equal((await f.game.match(a!.id, battle.id, clock)).body.battle.phase, "active");
    assert.equal((await f.database.query("SELECT count(*)::int AS n FROM online_player_slots")).rows[0]!.n, 2);
    assert.equal((await f.database.query("SELECT count(*)::int AS n FROM online_command_receipts WHERE command_id=$1", [request.commandId])).rows[0]!.n, 0);
    await f.database.query("ALTER TABLE online_reward_ledger DROP CONSTRAINT reject_rewards");
    assert.equal((await f.game.command(a!.id, battle.id, request, clock)).body.battle.phase, "finished");
});
test("deadline is rechecked after waiting for the transaction lock", async (t) => {
    const f = await gameFixture();
    t.after(() => f.close());
    const [a, b] = f.accounts;
    const inv = (await f.game.createInvite(a!.id, { commandId: randomUUID() }, clock)).body.invite;
    let s = (await f.game.acceptInvite(b!.id, inv.token, { commandId: randomUUID(), expectedVersion: 1 }, clock)).body.battle;
    for (const p of [a!, b!])
        s = (await f.game.command(p.id, s.id, intent(s.version, { type: "ready" }), clock)).body.battle;
    let actual = clock;
    const game = new OnlineGameService(f.database, { chatId: "-1001", threadId: 566, clock: () => actual });
    let unlock!: () => void;
    let entered!: () => void;
    const locked = new Promise<void>(r => { entered = r; });
    const hold = new Promise<void>(r => { unlock = r; });
    const blocker = f.database.transaction(async (tx) => { await tx.query("SELECT id FROM online_game_gate WHERE id=1 FOR UPDATE"); entered(); await hold; });
    await locked;
    const pending = game.command(a!.id, s.id, intent(s.version, { type: "press", command: { type: "zone", zone: "head" } }), clock);
    actual = s.deadline;
    unlock();
    await blocker;
    assert.equal((await pending).status, 410);
});
