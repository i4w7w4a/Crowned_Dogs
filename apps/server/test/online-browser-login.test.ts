import assert from "node:assert/strict";
import { test } from "node:test";
import { clock, embeddedDatabase } from "./online-fixtures.ts";
import { migrate, OnlineStore } from "../src/online/storage.ts";
import { BrowserLoginService } from "../src/online/browser-login.ts";
const identity = { id: "91", firstName: "Игрок", lastName: null, username: null };
test("browser bridge needs explicit confirmation, original nonce and one atomic consumption", async (t) => {
    const f = await embeddedDatabase();
    t.after(() => f.close());
    await migrate(f.database);
    const store = new OnlineStore(f.database);
    let actual = clock;
    const login = new BrowserLoginService(store, { origin: "https://example.test", botUsername: "GameTestBot", clock: () => actual });
    const token = "A".repeat(32);
    const started = await login.start({ inviteToken: token }, clock);
    assert.match(started.challengeId, /^[A-Za-z0-9_-]{32}$/);
    assert.equal(started.expiresAt, clock + 300000);
    assert.ok(!started.botUrl.includes(started.cookie));
    assert.deepEqual(await login.status(started.cookie, clock), { status: "pending", expiresAt: clock + 300000 });
    assert.equal((await login.describe(started.challengeId, clock))!.origin, "https://example.test");
    await assert.rejects(login.consume(started.cookie, clock), /pending/);
    assert.equal(await login.confirm(started.challengeId, identity, clock), "confirmed");
    assert.equal(await login.confirm(started.challengeId, { ...identity, id: "92" }, clock), "already_confirmed");
    await assert.rejects(login.consume(started.challengeId + "." + "B".repeat(43), clock), /expired/);
    await f.reopen();
    const raced = await Promise.allSettled([login.consume(started.cookie, clock + 1), login.consume(started.cookie, clock + 1)]);
    assert.equal(raced.filter(r => r.status === "fulfilled").length, 1);
    const result = (raced.find(r => r.status === "fulfilled") as PromiseFulfilledResult<any>).value;
    assert.equal(result.inviteToken, token);
    assert.equal(result.account.telegram.id, "91");
    assert.equal((await store.authenticate(result.token, clock + 2))!.id, result.account.id);
    assert.equal((await login.status(started.cookie, clock + 2)).status, "expired");
    const row = (await f.database.query("SELECT * FROM online_browser_challenges")).rows[0]!;
    assert.ok(!JSON.stringify(row).includes(started.cookie.split(".")[1]!));
    const next = await login.start({}, clock);
    assert.equal(await login.confirm(next.challengeId, identity, clock + 300000), "expired");
    await assert.rejects(login.consume(next.cookie, clock + 300000), /expired/);
    const delayed = await login.start({}, clock);
    await login.confirm(delayed.challengeId, identity, clock);
    let entered!: () => void;
    let release!: () => void;
    const held = new Promise<void>(r => { entered = r; });
    const gate = new Promise<void>(r => { release = r; });
    const blocker = f.database.transaction(async (tx) => { await tx.query("SELECT id FROM online_browser_challenges WHERE id=$1 FOR UPDATE", [delayed.challengeId]); entered(); await gate; });
    await held;
    const pending = login.consume(delayed.cookie, clock);
    actual = clock + 300000;
    release();
    await blocker;
    await assert.rejects(pending, /expired/);
});
test("failed session creation rolls back browser consume so the same browser can retry", async (t) => {
    const f = await embeddedDatabase();
    t.after(() => f.close());
    await migrate(f.database);
    const login = new BrowserLoginService(new OnlineStore(f.database), { origin: "https://example.test", botUsername: "GameTestBot", clock: () => clock });
    const started = await login.start({}, clock);
    await login.confirm(started.challengeId, identity, clock);
    await f.database.query("ALTER TABLE online_sessions ADD CONSTRAINT reject_session CHECK(false) NOT VALID");
    await assert.rejects(login.consume(started.cookie, clock));
    assert.equal((await login.status(started.cookie, clock)).status, "confirmed");
    assert.equal((await f.database.query("SELECT count(*)::int AS n FROM online_operators")).rows[0]!.n, 0);
    await f.database.query("ALTER TABLE online_sessions DROP CONSTRAINT reject_session");
    assert.equal((await login.consume(started.cookie, clock)).account.telegram.id, "91");
});
