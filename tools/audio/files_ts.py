"""packages/audio/src/files.generated.ts from sfx-sources.json; shared by build_sfx.py and ai_pack.py."""

import json
from pathlib import Path
from statistics import median

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "packages" / "audio" / "assets"

PUNCH_PREFIXES = ("shot-", "casing", "knife-", "hit-", "shield-", "miss-", "grenade-b", "step", "body-fall")


def write_files_ts(report):
    """packages/audio/src/files.generated.ts: length of every file and a trim that
    evens out the variants of one sound (shot-rifle-near-1..4 land equally hard)."""
    groups = {}
    for path, info in report.items():
        stem = path.rsplit(".", 1)[0]
        base = stem.rstrip("0123456789").rstrip("-") if stem[-1].isdigit() else stem
        groups.setdefault(base, []).append(path)
    lines = [
        "// Generated by tools/audio/build_sfx.py. Do not edit by hand.",
        "",
        "export interface FileInfo {",
        "  seconds: number;",
        "  /** Gain that evens out the variants of one sound, in dB. */",
        "  trimDb: number;",
        "  loop?: true;",
        "}",
        "",
        "export const FILES: Record<string, FileInfo> = {",
    ]
    for base, paths in sorted(groups.items()):
        key = "punch_db" if base.split("/")[-1].startswith(PUNCH_PREFIXES) else "lufs"
        mid = float(median(report[p][key] for p in paths))
        for p in sorted(paths):
            trim = max(-4.0, min(4.0, round(mid - report[p][key], 1))) if len(paths) > 1 else 0.0
            extra = ", loop: true" if report[p]["loop"] else ""
            lines.append(f'  "{p}": {{ seconds: {report[p]["seconds"]}, trimDb: {trim}{extra} }},')
    # The instructor's lines come from build_voice.py; keep them when the effects are rebuilt.
    voice = ASSETS / "voice-sources.json"
    if voice.exists():
        for p, info in sorted(json.loads(voice.read_text(encoding="utf-8")).items()):
            lines.append(f'  "{p}": {{ seconds: {info["seconds"]}, trimDb: 0.0 }},')
    lines += ["};", ""]
    (ROOT / "packages" / "audio" / "src" / "files.generated.ts").write_text("\n".join(lines))
